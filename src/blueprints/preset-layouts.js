export function presetEquipment(type, x, y, uid) {
  return presetLayouts[type].map(([asset, dx, dy]) => {
    const footprint = furniture[asset];
    if (!footprint) throw new Error('Asset de módulo desconhecido: ' + asset);
    return {
      id: uid(),
      kind: 'asset',
      asset,
      x: x + dx,
      y: y + dy,
      w: footprint.w,
      h: footprint.h,
      rotation: 0,
    };
  });
}
